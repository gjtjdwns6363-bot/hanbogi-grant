const MAX_Y = { sp: 4, fam: 3, biz: 3, corp: 2 }; // 묶음에서 Y가 이 개수 이하일 때만 "대상을 좁혔다"로 본다
// 코드 중 하나라도 Y이고, 그 묶음이 좁혀져 있으면 참
function pick(c, g, ...codes) {
  if (!c) return false;
  const n = GROUP[g].filter((k) => c[k] === 'Y').length;
  return n > 0 && n <= MAX_Y[g] && codes.some((k) => c[k] === 'Y');
}
